def load_progress() -> dict:
    if not PROGRESS_FILE.exists():
        return {"completed": {}, "last_seen": None}
    try:
        return json.loads(PROGRESS_FILE.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        print("تنبيه: تعذر قراءة ملف التقدم؛ ستبدأ جلسة تقدم جديدة.")
        return {"completed": {}, "last_seen": None}

def save_progress(progress: dict) -> None:
    PROGRESS_FILE.write_text(json.dumps(progress, ensure_ascii=False, indent=2), encoding="utf-8")

def get_module(module_id: str) -> dict:
    for module in MODULES:
        if module["id"] == module_id:
            return module
    raise SystemExit(f"لم أجد الوحدة: {module_id}. اعرض الوحدات بالأمر list.")

def command_list() -> None:
    progress = load_progress()
    print("\nأكاديمية PHARMAINTELLIGENCE — الوحدات التعليمية\n")
    for index, module in enumerate(MODULES, 1):
        result = progress["completed"].get(module["id"])
        status = f"مكتملة (أفضل نتيجة {result['best_score']}%)" if result else "لم تجتز الاختبار بعد"
        print(f"{index:02}. {module['id']:<20} | {module['title']} | {module['hours']} ساعة | {status}")
    print("\nابدأ بـ: py 00-START-HERE/academy.py lesson data-foundations")

def command_lesson(module_id: str) -> None:
    module = get_module(module_id)
    print(f"\n{module['title']}\nالمسار: {module['track']} | المستوى: {module['level']} | زمن مقترح: {module['hours']} ساعة\n")
    print("أهداف التعلم:")
    for objective in module["objectives"]:
        print(f"  • {objective}")
    print("\nالدرس:")
    for number, paragraph in enumerate(module["lesson"], 1):
        print(f"\n{number}. {paragraph}")
    print(f"\nالتطبيق العملي:\n{module['task']}")
    print("\nبعد إنجاز التطبيق شغّل الاختبار: py 00-START-HERE/academy.py quiz " + module_id)

def command_quiz(module_id: str) -> None:
    module = get_module(module_id)
    score = 0
    print(f"\nاختبار: {module['title']}\nأجب برقم الخيار. اكتب q للخروج دون حفظ.\n")
    for number, question in enumerate(module["questions"], 1):
        print(f"{number}. {question['q']}")
        for index, option in enumerate(question["options"], 1):
            print(f"   {index}) {option}")
        answer = input("إجابتك: ").strip().lower()
        if answer == "q":
            print("تم إيقاف الاختبار دون حفظ نتيجة.")
            return
        if not answer.isdigit() or not 1 <= int(answer) <= len(question["options"]):
            print("إجابة غير صالحة؛ ستحسب غير صحيحة.")
            chosen = -1
        else:
            chosen = int(answer) - 1
        if chosen == question["a"]:
            score += 1
            print("صحيح — " + question["why"] + "\n")
        else:
            print("غير صحيح. الإجابة: " + question["options"][question["a"]])
            print("التفسير: " + question["why"] + "\n")
    percent = round(score / len(module["questions"]) * 100)
    passed = percent >= 70
    print(f"النتيجة: {score}/{len(module['questions'])} = {percent}%")
    print("اجتزت الوحدة. انتقل للتطبيق التالي." if passed else "أعد قراءة الدرس وأعد الاختبار بعد مراجعة أخطائك.")
    progress = load_progress()
    previous = progress["completed"].get(module_id, {})
    best = max(percent, previous.get("best_score", 0))
    progress["completed"][module_id] = {
        "best_score": best,
        "last_score": percent,
        "passed": passed or previous.get("passed", False),
        "attempts": previous.get("attempts", 0) + 1,
        "last_attempt_utc": datetime.now(timezone.utc).isoformat(),
    }
    progress["last_seen"] = module_id
    save_progress(progress)

def command_progress() -> None:
    progress = load_progress()
    completed = sum(1 for item in progress["completed"].values() if item.get("passed"))
    print(f"\nالتقدم: {completed}/{len(MODULES)} وحدات اجتزت اختبارها.")
    for module in MODULES:
        result = progress["completed"].get(module["id"])
        if result:
            state = "اجتياز" if result.get("passed") else "تحتاج إعادة"
            print(f"- {module['title']}: {state} | أفضل {result['best_score']}% | محاولات {result['attempts']}")
        else:
            print(f"- {module['title']}: لم تبدأ")
    print(f"\nملف التقدم المحلي: {PROGRESS_FILE.resolve()}")

def main() -> None:
    parser = argparse.ArgumentParser(description="مدرب PHARMAINTELLIGENCE التعليمي")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list", help="عرض الوحدات وحالة التقدم")
    lesson_parser = sub.add_parser("lesson", help="عرض درس وتطبيق عملي")
    lesson_parser.add_argument("module_id")
    quiz_parser = sub.add_parser("quiz", help="بدء اختبار تفاعلي")
    quiz_parser.add_argument("module_id")
    sub.add_parser("progress", help="عرض سجل التقدم المحلي")
    args = parser.parse_args()
    if args.command == "list":
        command_list()
    elif args.command == "lesson":
        command_lesson(args.module_id)
    elif args.command == "quiz":
        command_quiz(args.module_id)
    elif args.command == "progress":
        command_progress()

if __name__ == "__main__":
    main()
